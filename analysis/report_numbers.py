"""Save manuscript numbers before typesetting; all observations come from CSVs."""
from collections import defaultdict
import csv
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
import numpy as np
from study.analyze import interval

ROOT = Path(__file__).resolve().parents[1]

def main():
    rows = list(csv.DictReader((ROOT / "results/raw.csv").open()))
    groups = defaultdict(list)
    for row in rows:
        groups[row["suite"], row["solid"], row["workload"], row["policy"]].append(row)
    values = {}
    for (suite, solid, work, policy), records in groups.items():
        prefix = f"{suite}/{solid}/{work}/{policy}/"
        for source, target in (("makespan_ms", "mean_ms"), ("messages", "messages"),
                               ("master_messages", "master_messages"),
                               ("migrated_tasks", "migrated_tasks")):
            values[prefix + target] = f"{np.mean([float(r[source]) for r in records]):.2f}"
        values[prefix + "bytes_mb"] = f"{np.mean([float(r['bytes']) for r in records])/1e6:.2f}"
        values[prefix + "master_messages_integer"] = f"{np.mean([float(r['master_messages']) for r in records]):.0f}"
        static = {int(r["seed"]): float(r["makespan_ms"])
                  for r in groups[suite, solid, work, "static"]}
        avg, lo, hi = interval([static[int(r["seed"])] / float(r["makespan_ms"]) for r in records])
        for name, value in (("speedup", avg), ("speed_low", lo), ("speed_high", hi)):
            values[prefix + name] = f"{value:.3f}"
    for row in csv.DictReader((ROOT / "results/topology_summary.csv").open()):
        prefix = f"topology/{row['solid']}/{row['workload']}/{row['policy']}/{row['topology']}/"
        for source, target in (("platonic_over_control", "ratio"), ("ratio_ci_low", "low"),
                               ("ratio_ci_high", "high")):
            values[prefix + target] = f"{float(row[source]):.3f}"
    for work in ("lognormal", "clustered"):
        effect = [float(values[f"main/{s}/{work}/neighbor_push/speedup"])
                  for s in ("tetrahedron", "cube", "octahedron", "dodecahedron", "icosahedron")]
        values[f"range/{work}/low"] = f"{min(effect):.3f}"
        values[f"range/{work}/high"] = f"{max(effect):.3f}"
    test_path = ROOT / "results/tests.xml"
    if not test_path.exists():
        raise RuntimeError("Run make check before manuscript generation; test counts require a completed suite.")
    suites = list(ET.parse(test_path).getroot().iter("testsuite"))
    assert all(int(s.attrib.get(k, 0)) == 0 for s in suites for k in ("failures", "errors", "skipped"))
    values["validation/tests"] = str(sum(int(s.attrib["tests"]) for s in suites))
    values["validation/runs"] = f"{len(rows) + sum(1 for _ in csv.DictReader((ROOT/'results/topology.csv').open())):,}"
    primary_cells = sorted({(s,w) for suite,s,w,p in groups if suite == "main" and w != "constant"})
    winners = 0
    for solid, work in primary_cells:
        means = {p: np.mean([float(r["makespan_ms"]) for r in records])
                 for (suite,s,w,p),records in groups.items() if suite == "main" and s == solid and w == work}
        winners += min(means, key=means.get) == "neighbor_push"
    values["rank/variable_cells"] = str(len(primary_cells))
    values["rank/push_lowest_mean"] = str(winners)
    stats = json.loads((ROOT / "results/exploratory_statistics.json").read_text())
    values["statistics/family"] = str(len(stats))
    for comparator in ("static", "neighbor_steal"):
        subset = [r for r in stats if r["comparator"] == comparator]
        values[f"statistics/{comparator}/cells"] = str(len(subset))
        for outcome in ("difference", "equivalence"):
            values[f"statistics/{comparator}/{outcome}"] = str(sum(
                r[outcome + "_holm_below_0_05"] for r in subset))
    hashes = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
              for p in (ROOT / "results/raw.csv", ROOT / "results/topology.csv")}
    (ROOT / "results/numbers.json").write_text(json.dumps({"source_hashes": hashes, "values": values}, indent=2) + "\n")
    tex = [r"% Generated by analysis.report_numbers; observations must not be hand-edited.",
           r"\newcommand{\datum}[1]{\csname observation:#1\endcsname}"]
    tex.extend(r"\expandafter\def\csname observation:" + k + r"\endcsname{" + v + "}" for k, v in sorted(values.items()))
    (ROOT / "paper/numbers.tex").write_text("\n".join(tex) + "\n")
    print(f"Saved {len(values)} manuscript values and raw source hashes.")

if __name__ == "__main__": main()
